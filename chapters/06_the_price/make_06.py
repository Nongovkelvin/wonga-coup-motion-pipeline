# make_06.py: writes build_06_price_1.jsx from the chapter 05 build (setup, helpers incl. 02/03's new ones, master pass) + media06/body06.jsxpart. Overnight runner (Nongov Kelvin), 5 Nov 2026.
import os
B = os.path.dirname(os.path.abspath(__file__))
src = open(B + "/../../05_seventh_march/build/build_05_march_1.jsx", encoding="utf-8").read()
body = open(B + "/body06.jsxpart", encoding="utf-8").read()
i0 = src.index("#target aftereffects")
i1 = src.index("// =====================================================================\n// CHAPTER 05 SUNDAY 7 MARCH 2004")
i2 = src.index('log("segments built: " + SEG.length);')
H, M2 = src[i0:i1], src[i2:]
rep = [
    ("build_05_march_1.log", "build_06_price_1.log"),
    ('CH = AS + "05_seventh_march/"', 'CH = AS + "06_the_price/"'),
    ('SPECIAL = AS + "_special/05_seventh_march/"', 'SPECIAL = AS + "_special/06_the_price/"'),
    ("var T0 = 1200.6, T1 = 1466.3;", "var T0 = 1466.3, T1 = 1719.2;"),
    ('CF = folder("05 Sunday 7 March", VB)', 'CF = folder("06 The price", VB)'),
    ('var MN = "05 SUNDAY 7 MARCH 2004 20:01-24:26";', 'var MN = "06 THE PRICE 24:26-28:39";'),
    ("/^05a (parts|paper \\+ stock inserts) 20:01-24:26$/", "/^06a (parts|paper \\+ stock inserts) 24:26-28:39$/"),
    ('folder("05a parts 20:01-24:26", CF)', 'folder("06a parts 24:26-28:39", CF)'),
    ('folder("05a paper + stock inserts 20:01-24:26", CF)', 'folder("06a paper + stock inserts 24:26-28:39", CF)'),
    ('folder("media 05 sunday 7 march", VB)', 'folder("media 06 the price", VB)'),
    ('app.beginUndoGroup("Build 05 Sunday 7 March 20:01-24:26 (build 1)");', 'app.beginUndoGroup("Build 06 The price 24:26-28:39 (build 1)");'),
]
for a, b in rep:
    if a not in H: raise SystemExit("not found: " + a)
    H = H.replace(a, b)
m0 = H.index("var P0 = AS"); m1 = H.index('log("media imported");')
MEDIA = open(B + "/media06.jsxpart", encoding="utf-8").read()
H = H[:m0] + MEDIA + H[m1:]
out = "// WONGA COUP - CHAPTER 06 THE PRICE: Black Beach, Chikurubi, the trials, Pomfret, Beitbridge - first cut 24:26.3-28:39.2 (1466.3-1719.2 s) - BUILD 1\n"
out += "// Written by the overnight runner (Nongov Kelvin), 5 Nov 2026. Generated by make_06.py from the ch 05 build (setup, helpers, master) + media06/body06.jsxpart.\n"
out += "// Run in AE 2025 only with 'ae Wonga.aep' open, under the AE lock (build/run_ae.sh). Re-running replaces only its own master and '06a ...' folders. Nothing is saved.\n"
out += H + "\n" + body + "\n" + M2
for bad in ["05 SUNDAY", "05a ", "1200.6"]:
    if bad in body or bad in M2: print("WARN leftover", bad)
open(B + "/build_06_price_1.jsx", "w", encoding="utf-8").write(out)
print("ok", len(out.split("\n")))
