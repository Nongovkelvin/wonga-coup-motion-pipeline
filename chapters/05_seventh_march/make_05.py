# make_05.py: writes build_05_march_1.jsx from the chapter 04 build (setup, helpers incl. 02/03's new ones, master pass) + media05/body05.jsxpart. Overnight runner (Nongov Kelvin), 5 Nov 2026.
import os
B = os.path.dirname(os.path.abspath(__file__))
src = open(B + "/../../04_the_leaks/build/build_04_leaks_1.jsx", encoding="utf-8").read()
body = open(B + "/body05.jsxpart", encoding="utf-8").read()
i0 = src.index("#target aftereffects")
i1 = src.index("// =====================================================================\n// CHAPTER 04 THE WORST KEPT SECRET")
i2 = src.index('log("segments built: " + SEG.length);')
H, M2 = src[i0:i1], src[i2:]
rep = [
    ("build_04_leaks_1.log", "build_05_march_1.log"),
    ('CH = AS + "04_the_leaks/"', 'CH = AS + "05_seventh_march/"'),
    ('SPECIAL = AS + "_special/04_the_leaks/"', 'SPECIAL = AS + "_special/05_seventh_march/"'),
    ("var T0 = 898.2, T1 = 1200.6;", "var T0 = 1200.6, T1 = 1466.3;"),
    ('CF = folder("04 The leaks", VB)', 'CF = folder("05 Sunday 7 March", VB)'),
    ('var MN = "04 THE WORST KEPT SECRET 14:58-20:01";', 'var MN = "05 SUNDAY 7 MARCH 2004 20:01-24:26";'),
    ("/^04a (parts|paper \\+ stock inserts) 14:58-20:01$/", "/^05a (parts|paper \\+ stock inserts) 20:01-24:26$/"),
    ('folder("04a parts 14:58-20:01", CF)', 'folder("05a parts 20:01-24:26", CF)'),
    ('folder("04a paper + stock inserts 14:58-20:01", CF)', 'folder("05a paper + stock inserts 20:01-24:26", CF)'),
    ('folder("media 04 the leaks", VB)', 'folder("media 05 sunday 7 march", VB)'),
    ('app.beginUndoGroup("Build 04 The leaks 14:58-20:01 (build 1)");', 'app.beginUndoGroup("Build 05 Sunday 7 March 20:01-24:26 (build 1)");'),
]
for a, b in rep:
    if a not in H: raise SystemExit("not found: " + a)
    H = H.replace(a, b)
m0 = H.index("var P0 = AS"); m1 = H.index('log("media imported");')
MEDIA = open(B + "/media05.jsxpart", encoding="utf-8").read()
H = H[:m0] + MEDIA + H[m1:]
out = "// WONGA COUP - CHAPTER 05 SUNDAY 7 MARCH 2004: Wonderboom, the King Air, the Harare sting, Mali, the Canaries, Malabo, Obiang on TV - first cut 20:00.6-24:26.3 (1200.6-1466.3 s) - BUILD 1\n"
out += "// Written by the overnight runner (Nongov Kelvin), 5 Nov 2026. Generated by make_05.py from the ch 04 build (setup, helpers, master) + media05/body05.jsxpart.\n"
out += "// Run in AE 2025 only with 'ae Wonga.aep' open, under the AE lock (build/run_ae.sh). Re-running replaces only its own master and '05a ...' folders. Nothing is saved.\n"
out += H + "\n" + body + "\n" + M2
for bad in ["04 THE WORST", "04a ", "898.2"]:
    if bad in body or bad in M2: print("WARN leftover", bad)
open(B + "/build_05_march_1.jsx", "w", encoding="utf-8").write(out)
print("ok", len(out.split("\n")))
