# make_09.py: writes build_09_epilogue_1.jsx from the chapter 08 build (setup, helpers incl. 02/03's new ones, master pass) + media09/body09.jsxpart. Overnight runner (Nongov Kelvin), 5 Nov 2026.
import os
B = os.path.dirname(os.path.abspath(__file__))
src = open(B + "/../../08_black_beach/build/build_08_beach_1.jsx", encoding="utf-8").read()
body = open(B + "/body09.jsxpart", encoding="utf-8").read()
i0 = src.index("#target aftereffects")
i1 = src.index("// =====================================================================\n// CHAPTER 08 BLACK BEACH")
i2 = src.index('log("segments built: " + SEG.length);')
H, M2 = src[i0:i1], src[i2:]
rep = [
    ('build_08_beach_1.log', 'build_09_epilogue_1.log'),
    ('CH = AS + "08_black_beach/"', 'CH = AS + "09_epilogue/"'),
    ('SPECIAL = AS + "_special/08_black_beach/"', 'SPECIAL = AS + "_special/09_epilogue/"'),
    ('var T0 = 1992.8, T1 = 2211.6;', 'var T0 = 2211.6, T1 = 2379.2;'),
    ('CF = folder("08 Black Beach", VB)', 'CF = folder("09 Nothing has changed", VB)'),
    ('var MN = "08 BLACK BEACH 33:13-36:52";', 'var MN = "09 NOTHING HAS CHANGED 36:52-39:36";'),
    ('/^08a (parts|paper \\+ stock inserts) 33:13-36:52$/', '/^09a (parts|paper \\+ stock inserts) 36:52-39:36$/'),
    ('folder("08a parts 33:13-36:52", CF)', 'folder("09a parts 36:52-39:36", CF)'),
    ('folder("08a paper + stock inserts 33:13-36:52", CF)', 'folder("09a paper + stock inserts 36:52-39:36", CF)'),
    ('folder("media 08 black beach", VB)', 'folder("media 09 epilogue", VB)'),
    ('app.beginUndoGroup("Build 08 Black Beach 33:13-36:52 (build 1)");', 'app.beginUndoGroup("Build 09 Nothing has changed 36:52-39:36 (build 1)");'),
]
for a, b in rep:
    if a not in H: raise SystemExit("not found: " + a)
    H = H.replace(a, b)
m0 = H.index("var P0 = AS"); m1 = H.index('log("media imported");')
MEDIA = open(B + "/media09.jsxpart", encoding="utf-8").read()
H = H[:m0] + MEDIA + H[m1:]
out = "// WONGA COUP - CHAPTER 09 NOTHING HAS CHANGED: Riggs, Rice, the deaths of Calil and Mann, Obiang and Teodorin today, Jude's close - first cut 36:51.6-39:35.7 (2211.6-2375.7 s), master to 2379.2 for the end still and black - BUILD 1\n"
out += "// Written by the overnight runner (Nongov Kelvin), 5 Nov 2026. Generated by make_09.py from the ch 08 build (setup, helpers, master) + media09/body09.jsxpart.\n"
out += "// Run in AE 2025 only with 'ae Wonga.aep' open, under the AE lock (build/run_ae.sh). Re-running replaces only its own master and '09a ...' folders. Nothing is saved.\n"
out += H + "\n" + body + "\n" + M2
for bad in ["08 BLACK", "08a ", "1992.8"]:
    if bad in body or bad in M2: print("WARN leftover", bad)
open(B + "/build_09_epilogue_1.jsx", "w", encoding="utf-8").write(out)
print("ok", len(out.split("\n")))
