# make_08.py: writes build_08_beach_1.jsx from the chapter 07 build (setup, helpers incl. 02/03's new ones, master pass) + media08/body08.jsxpart. Overnight runner (Nongov Kelvin), 5 Nov 2026.
import os
B = os.path.dirname(os.path.abspath(__file__))
src = open(B + "/../../07_wonga/build/build_07_wonga_1.jsx", encoding="utf-8").read()
body = open(B + "/body08.jsxpart", encoding="utf-8").read()
i0 = src.index("#target aftereffects")
i1 = src.index("// =====================================================================\n// CHAPTER 07 A LARGE SPLODGE OF WONGA")
i2 = src.index('log("segments built: " + SEG.length);')
H, M2 = src[i0:i1], src[i2:]
rep = [
    ('build_07_wonga_1.log', 'build_08_beach_1.log'),
    ('CH = AS + "07_wonga/"', 'CH = AS + "08_black_beach/"'),
    ('SPECIAL = AS + "_special/07_wonga/"', 'SPECIAL = AS + "_special/08_black_beach/"'),
    ('var T0 = 1719.2, T1 = 1992.8;', 'var T0 = 1992.8, T1 = 2211.6;'),
    ('CF = folder("07 Wonga", VB)', 'CF = folder("08 Black Beach", VB)'),
    ('var MN = "07 A LARGE SPLODGE OF WONGA 28:39-33:13";', 'var MN = "08 BLACK BEACH 33:13-36:52";'),
    ('/^07a (parts|paper \\+ stock inserts) 28:39-33:13$/', '/^08a (parts|paper \\+ stock inserts) 33:13-36:52$/'),
    ('folder("07a parts 28:39-33:13", CF)', 'folder("08a parts 33:13-36:52", CF)'),
    ('folder("07a paper + stock inserts 28:39-33:13", CF)', 'folder("08a paper + stock inserts 33:13-36:52", CF)'),
    ('folder("media 07 wonga", VB)', 'folder("media 08 black beach", VB)'),
    ('app.beginUndoGroup("Build 07 Wonga 28:39-33:13 (build 1)");', 'app.beginUndoGroup("Build 08 Black Beach 33:13-36:52 (build 1)");'),
]
for a, b in rep:
    if a not in H: raise SystemExit("not found: " + a)
    H = H.replace(a, b)
m0 = H.index("var P0 = AS"); m1 = H.index('log("media imported");')
MEDIA = open(B + "/media08.jsxpart", encoding="utf-8").read()
H = H[:m0] + MEDIA + H[m1:]
out = "// WONGA COUP - CHAPTER 08 BLACK BEACH: the extradition, Channel 4 in Black Beach, the trial, the pardon - first cut 33:12.8-36:51.6 (1992.8-2211.6 s) - BUILD 1\n"
out += "// Written by the overnight runner (Nongov Kelvin), 5 Nov 2026. Generated by make_08.py from the ch 07 build (setup, helpers, master) + media08/body08.jsxpart.\n"
out += "// Run in AE 2025 only with 'ae Wonga.aep' open, under the AE lock (build/run_ae.sh). Re-running replaces only its own master and '08a ...' folders. Nothing is saved.\n"
out += H + "\n" + body + "\n" + M2
for bad in ["07 A LARGE", "07a ", "1719.2"]:
    if bad in body or bad in M2: print("WARN leftover", bad)
open(B + "/build_08_beach_1.jsx", "w", encoding="utf-8").write(out)
print("ok", len(out.split("\n")))
