# make_04.py: writes build_04_leaks_1.jsx from the chapter 03 build (setup, helpers incl. 02/03's new ones, master pass) + media04/body04.jsxpart. Overnight runner (Nongov Kelvin), 5 Nov 2026.
import os
B = os.path.dirname(os.path.abspath(__file__))
src = open(B + "/../../03_the_army/build/build_03_army_1.jsx", encoding="utf-8").read()
body = open(B + "/body04.jsxpart", encoding="utf-8").read()
i0 = src.index("#target aftereffects")
i1 = src.index("// =====================================================================\n// CHAPTER 03 THE ARMY")
i2 = src.index('log("segments built: " + SEG.length);')
H, M2 = src[i0:i1], src[i2:]
rep = [
    ("build_03_army_1.log", "build_04_leaks_1.log"),
    ('CH = AS + "03_the_army/"', 'CH = AS + "04_the_leaks/"'),
    ('SPECIAL = AS + "_special/03_the_army/"', 'SPECIAL = AS + "_special/04_the_leaks/"'),
    ("var T0 = 637.7, T1 = 898.2;", "var T0 = 898.2, T1 = 1200.6;"),
    ('CF = folder("03 The army", VB)', 'CF = folder("04 The leaks", VB)'),
    ('var MN = "03 THE ARMY 10:38-14:58";', 'var MN = "04 THE WORST KEPT SECRET 14:58-20:01";'),
    ("/^03a (parts|paper \\+ stock inserts) 10:38-14:58$/", "/^04a (parts|paper \\+ stock inserts) 14:58-20:01$/"),
    ('folder("03a parts 10:38-14:58", CF)', 'folder("04a parts 14:58-20:01", CF)'),
    ('folder("03a paper + stock inserts 10:38-14:58", CF)', 'folder("04a paper + stock inserts 14:58-20:01", CF)'),
    ('folder("media 03 the army", VB)', 'folder("media 04 the leaks", VB)'),
    ('app.beginUndoGroup("Build 03 The army 10:38-14:58 (build 1)");', 'app.beginUndoGroup("Build 04 The leaks 14:58-20:01 (build 1)");'),
]
for a, b in rep:
    if a not in H: raise SystemExit("not found: " + a)
    H = H.replace(a, b)
m0 = H.index("var P0 = AS"); m1 = H.index('log("media imported");')
MEDIA = open(B + "/media04.jsxpart", encoding="utf-8").read()
H = H[:m0] + MEDIA + H[m1:]
H = H.replace("app.beginUndoGroup(", "app.beginSuppressDialogs();\napp.beginUndoGroup(", 1)
M2 = M2.replace("app.endUndoGroup();", "app.endUndoGroup();\napp.endSuppressDialogs(false);", 1)
out = "// WONGA COUP - CHAPTER 04 THE WORST KEPT SECRET: Smith's reports, Kershaw and Morgan, Malabo, the emails, Spain's ships, the February abort - first cut 14:58.2-20:00.6 (898.2-1200.6 s) - BUILD 1\n"
out += "// Written by the overnight runner (Nongov Kelvin), 5 Nov 2026. Generated by make_04.py from the ch 03 build (setup, helpers, master) + media04/body04.jsxpart.\n"
out += "// Run in AE 2025 only with 'ae Wonga.aep' open, under the AE lock (build/run_ae.sh). Re-running replaces only its own master and '04a ...' folders. Nothing is saved.\n"
out += H + "\n" + body + "\n" + M2
for bad in ["03 THE ARMY", "03a ", "637.7"]:
    if bad in body or bad in M2: print("WARN leftover", bad)
open(B + "/build_04_leaks_1.jsx", "w", encoding="utf-8").write(out)
print("ok", len(out.split("\n")))
