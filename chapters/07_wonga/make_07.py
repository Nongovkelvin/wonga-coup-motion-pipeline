# make_07.py: writes build_07_wonga_1.jsx from the chapter 06 build (setup, helpers incl. 02/03's new ones, master pass) + media07/body07.jsxpart. Overnight runner (Nongov Kelvin), 5 Nov 2026.
import os
B = os.path.dirname(os.path.abspath(__file__))
src = open(B + "/../../06_the_price/build/build_06_price_1.jsx", encoding="utf-8").read()
body = open(B + "/body07.jsxpart", encoding="utf-8").read()
i0 = src.index("#target aftereffects")
i1 = src.index("// =====================================================================\n// CHAPTER 06 THE PRICE")
i2 = src.index('log("segments built: " + SEG.length);')
H, M2 = src[i0:i1], src[i2:]
rep = [
    ('build_06_price_1.log', 'build_07_wonga_1.log'),
    ('CH = AS + "06_the_price/"', 'CH = AS + "07_wonga/"'),
    ('SPECIAL = AS + "_special/06_the_price/"', 'SPECIAL = AS + "_special/07_wonga/"'),
    ('var T0 = 1466.3, T1 = 1719.2;', 'var T0 = 1719.2, T1 = 1992.8;'),
    ('CF = folder("06 The price", VB)', 'CF = folder("07 Wonga", VB)'),
    ('var MN = "06 THE PRICE 24:26-28:39";', 'var MN = "07 A LARGE SPLODGE OF WONGA 28:39-33:13";'),
    ('/^06a (parts|paper \\+ stock inserts) 24:26-28:39$/', '/^07a (parts|paper \\+ stock inserts) 28:39-33:13$/'),
    ('folder("06a parts 24:26-28:39", CF)', 'folder("07a parts 28:39-33:13", CF)'),
    ('folder("06a paper + stock inserts 24:26-28:39", CF)', 'folder("07a paper + stock inserts 28:39-33:13", CF)'),
    ('folder("media 06 the price", VB)', 'folder("media 07 wonga", VB)'),
    ('app.beginUndoGroup("Build 06 The price 24:26-28:39 (build 1)");', 'app.beginUndoGroup("Build 07 Wonga 28:39-33:13 (build 1)");'),
]
for a, b in rep:
    if a not in H: raise SystemExit("not found: " + a)
    H = H.replace(a, b)
m0 = H.index("var P0 = AS"); m1 = H.index('log("media imported");')
MEDIA = open(B + "/media07.jsxpart", encoding="utf-8").read()
H = H[:m0] + MEDIA + H[m1:]
out = "// WONGA COUP - CHAPTER 07 A LARGE SPLODGE OF WONGA: the letter, Scratcher and Smelly, Thatcher's arrest and plea, the London case, Straw - first cut 28:39.2-33:12.8 (1719.2-1992.8 s) - BUILD 1\n"
out += "// Written by the overnight runner (Nongov Kelvin), 5 Nov 2026. Generated by make_07.py from the ch 06 build (setup, helpers, master) + media07/body07.jsxpart.\n"
out += "// Run in AE 2025 only with 'ae Wonga.aep' open, under the AE lock (build/run_ae.sh). Re-running replaces only its own master and '07a ...' folders. Nothing is saved.\n"
out += H + "\n" + body + "\n" + M2
for bad in ["06 THE PRICE", "06a ", "1466.3"]:
    if bad in body or bad in M2: print("WARN leftover", bad)
open(B + "/build_07_wonga_1.jsx", "w", encoding="utf-8").write(out)
print("ok", len(out.split("\n")))
