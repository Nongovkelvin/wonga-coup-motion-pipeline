# make_03.py: writes build_03_army_1.jsx from the chapter 02 build (setup, helpers incl. 02's new ones, master pass) + body03.jsxpart (chapter 03 shots). wonga-03, 5 Nov 2026.
import os
B = os.path.dirname(os.path.abspath(__file__))
src = open(B + "/../../02_london/build/build_02_london_1.jsx", encoding="utf-8").read()
body = open(B + "/body03.jsxpart", encoding="utf-8").read()
i0 = src.index("#target aftereffects")
i1 = src.index("// =====================================================================\n// CHAPTER 02 THE LONDON MONEY")
i2 = src.index('log("segments built: " + SEG.length);')
H, M2 = src[i0:i1], src[i2:]
rep = [
    ("build_02_london_1.log", "build_03_army_1.log"),
    ('CH = AS + "02_london/"', 'CH = AS + "03_the_army/"'),
    ('SPECIAL = AS + "_special/02_london/"', 'SPECIAL = AS + "_special/03_the_army/"'),
    ("var T0 = 400.6, T1 = 637.7;", "var T0 = 637.7, T1 = 898.2;"),
    ('CF = folder("02 The London money", VB)', 'CF = folder("03 The army", VB)'),
    ('var MN = "02 THE LONDON MONEY 6:41-10:38";', 'var MN = "03 THE ARMY 10:38-14:58";'),
    ("/^02a (parts|paper \\+ stock inserts) 6:41-10:38$/", "/^03a (parts|paper \\+ stock inserts) 10:38-14:58$/"),
    ('folder("02a parts 6:41-10:38", CF)', 'folder("03a parts 10:38-14:58", CF)'),
    ('folder("02a paper + stock inserts 6:41-10:38", CF)', 'folder("03a paper + stock inserts 10:38-14:58", CF)'),
    ('folder("media 02 the london money", VB)', 'folder("media 03 the army", VB)'),
    ('app.beginUndoGroup("Build 02 The London money 6:41-10:38 (build 1)");', 'app.beginUndoGroup("Build 03 The army 10:38-14:58 (build 1)");'),
]
for a, b in rep:
    if a not in H: raise SystemExit("not found: " + a)
    H = H.replace(a, b)
m0 = H.index("var P0 = AS"); m1 = H.index('log("media imported");')
MEDIA = open(B + "/media03.jsxpart", encoding="utf-8").read()
H = H[:m0] + MEDIA + H[m1:]
out = "// WONGA COUP - CHAPTER 03 THE ARMY: Pomfret, 32 Battalion, du Toit, the 727, the ZDI arsenal - first cut 10:37.7-14:58.2 (637.7-898.2 s) - BUILD 1\n"
out += "// Written by chapter session wonga-03 (Nongov Kelvin), 5 Nov 2026. Generated by make_03.py from the ch 02 build (setup, helpers, master) + media03/body03.jsxpart.\n"
out += "// Run in AE 2025 only with 'ae Wonga.aep' open, under the AE lock (build/run_ae.sh). Re-running replaces only its own master and '03a ...' folders. Nothing is saved.\n"
out += H + "\n" + body + "\n" + M2
for bad in ["02 THE LONDON", "02a ", "400.6"]:
    if bad in body or bad in M2: print("WARN leftover", bad)
open(B + "/build_03_army_1.jsx", "w", encoding="utf-8").write(out)
print("ok", len(out.split("\n")))
